#!/usr/bin/env node
/**
 * build-site-data.mjs: generate docs/site-data.js, the one data file behind
 * the landing page (docs/index.html) and the case study (docs/case-study.html).
 *
 * Those two pages type no figures. Every number and every drawing on them is
 * assembled in the browser from this file, and this file comes from audit()
 * and buildField() run on the two committed, redacted study snapshots, plus
 * the verbatim output of `falloff report` for each.
 *
 * The pages compare a large metro with a small town, so the script needs to
 * know which study is which. It reads that from each study's study.json
 * (`role: "metro"` or `role: "quiet"`); no folder name appears in this file.
 *
 * Deterministic: same snapshots in, same bytes out. No clock, no network.
 *
 * Usage:
 *   node scripts/build-site-data.mjs           write docs/site-data.js
 *   node scripts/build-site-data.mjs --check   exit 1 if the file on disk is stale
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

import { loadStudies } from './studies-index.mjs';
import { buildField } from './build-field.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'docs', 'site-data.js');

function study({ folder, snap, meta, audit: a }) {
  if (!a.ok) throw new Error(`${folder} fails audit; the site never draws a study its own auditor rejects`);
  const field = buildField(snap);
  const report = execFileSync(process.execPath, [join(ROOT, 'bin', 'falloff.mjs'), 'report', join('studies', folder, 'snapshot.json')], { cwd: ROOT, encoding: 'utf8' });
  return {
    folder,
    place: meta.place,
    query: snap.query,
    observed: String(snap.startedAt).slice(0, 10),
    auditOk: a.ok,
    report: report.replace(/\r\n/g, '\n'),
    metrics: a.metrics,
    ringRadiiKm: snap.method.ringRadiiKm,
    pointsPerRing: snap.method.pointsPerRing,
    readings: snap.readings.map((r) => ({ ring: r.ring, index: r.index, dKm: r.dKm, bearing: r.bearing, status: r.status, rank: r.rank ?? null })),
    field: field.rows.map((r) => ({ label: r.label, isTarget: r.isTarget, found: r.found, measured: r.measured, bestRank: r.bestRank, rating: r.rating, reviews: r.reviews, points: r.points })),
  };
}

export function buildSiteData() {
  const studies = loadStudies();
  const pick = (role) => {
    const hits = studies.filter((s) => s.meta.role === role);
    if (hits.length !== 1) throw new Error(`expected exactly one study with role "${role}" in its study.json, found ${hits.length}`);
    return study(hits[0]);
  };
  return { metro: pick('metro'), quiet: pick('quiet') };
}

export const siteDataJs = (data) =>
  `// Generated by scripts/build-site-data.mjs. Do not edit: run \`npm run site-data\`.\nwindow.FALLOFF_SITE = ${JSON.stringify(data)};\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = siteDataJs(buildSiteData());
  if (process.argv.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('docs/site-data.js is stale. Run: npm run site-data'); process.exit(1); }
    console.log('docs/site-data.js is current');
  } else {
    writeFileSync(OUT, text);
    console.log(`docs/site-data.js written (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
